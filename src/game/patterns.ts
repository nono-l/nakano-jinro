export const SLOTS = ["join", "voice", "audit", "status", "about", "nick", "react", "stamp", "image", "file", "pin"] as const;

export type ClueSlot = (typeof SLOTS)[number];

export type CluePattern = {
  id: string;
  inner: string;
  tier: 0 | 1 | 2;
  slot: ClueSlot;
  text: string;
};

type Trio = [string, string, string];

function rows(inner: string, blocks: Record<ClueSlot, Trio>): CluePattern[] {
  const out: CluePattern[] = [];
  for (const slot of SLOTS) {
    blocks[slot].forEach((text, tier) => {
      out.push({ id: `${inner}-${slot}-${tier}`, inner, tier: tier as 0 | 1 | 2, slot, text });
    });
  }
  return out;
}

