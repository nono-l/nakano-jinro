export function assertPatterns(): void {
  if (PATTERNS.length < 300) throw new Error(`patterns ${PATTERNS.length}`);
  const ids = new Set(PATTERNS.map((pattern) => pattern.id));
  if (ids.size !== PATTERNS.length) throw new Error("duplicate pattern id");
  const inners = ["girl", "it", "boss", "gamer", "baseball", "family", "stock", "sauna", "train", "otaku"];
  for (const inner of inners) {
    for (const slot of SLOTS) {
      for (const tier of [0, 1, 2]) {
        const found = PATTERNS.filter((pattern) => pattern.inner === inner && pattern.slot === slot && pattern.tier === tier);
        if (found.length !== 1) throw new Error(`pattern ${inner} ${slot} ${tier}`);
      }
    }
    if (inner !== "girl") {
      const blob = PATTERNS.filter((pattern) => pattern.inner === inner).map((pattern) => pattern.text).join("\n");
      if (blob.includes("プリン") || blob.includes("2004")) throw new Error(`pattern leak ${inner}`);
    }
  }
}
